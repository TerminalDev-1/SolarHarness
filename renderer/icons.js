export function icon(name, className = "") {
  const span = document.createElement("span");
  span.className = `icon ${className}`.trim();
  span.innerHTML = svg(name);
  return span;
}

export function svg(name) {
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths[name] ?? paths.dot}</svg>`;
}

/** Fills every `<span data-icon="name">` placeholder in the static HTML. */
export function hydrateIcons(root = document) {
  for (const element of root.querySelectorAll("[data-icon]")) element.innerHTML = svg(element.dataset.icon);
}
